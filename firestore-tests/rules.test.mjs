import { initializeTestEnvironment, assertFails, assertSucceeds } from "@firebase/rules-unit-testing";
import fs from "node:fs";
import { Timestamp } from "firebase/firestore";
import { doc, getDoc, setDoc, deleteDoc, Timestamp as T } from "firebase/firestore";
const env = await initializeTestEnvironment({ projectId: "demo-nelly", firestore: { rules: fs.readFileSync("firestore.rules","utf8"), host:"127.0.0.1", port:8089 } });
await env.withSecurityRulesDisabled(async (c) => {
  const d = c.firestore();
  await setDoc(doc(d,"userShops/uA"),{shopId:"A"}); await setDoc(doc(d,"userShops/uB"),{shopId:"B"}); await setDoc(doc(d,"userShops/uX"),{shopId:"X"});
  await setDoc(doc(d,"shops/A"),{name:"A",activeUntil:T.fromMillis(Date.now()+864e5)});
  await setDoc(doc(d,"shops/B"),{name:"B",activeUntil:T.fromMillis(Date.now()+864e5)});
  await setDoc(doc(d,"shops/X"),{name:"X",activeUntil:T.fromMillis(Date.now()-864e5)});
  await setDoc(doc(d,"shops/A/nelly_sales/s1"),{total:5});
  await setDoc(doc(d,"nelly_sales/old"),{total:1});
});
const a = env.authenticatedContext("uA").firestore(), x = env.authenticatedContext("uX").firestore(), anon = env.unauthenticatedContext().firestore();
const r = [];
const t = async (n, p) => { try { await p; r.push("PASS "+n);} catch(e){ r.push("FAIL "+n+" "+e.message.slice(0,80)); } };
await t("A reads own", assertSucceeds(getDoc(doc(a,"shops/A/nelly_sales/s1"))));
await t("A writes own", assertSucceeds(setDoc(doc(a,"shops/A/nelly_sales/s2"),{total:1})));
await t("A deletes own", assertSucceeds(deleteDoc(doc(a,"shops/A/nelly_sales/s2"))));
await t("A cannot read B", assertFails(getDoc(doc(a,"shops/B/nelly_sales/s1"))));
await t("A cannot write B", assertFails(setDoc(doc(a,"shops/B/nelly_sales/z"),{})));
await t("A cannot reset its AI quota", assertFails(setDoc(doc(a,"shops/A/aiUsage/2026-10-09"),{calls:0})));
await t("A cannot self-link userShops", assertFails(setDoc(doc(a,"userShops/uA"),{shopId:"B"})));
await t("A cannot extend subscription", assertFails(setDoc(doc(a,"shops/A"),{activeUntil:T.fromMillis(Date.now()+9e12)},{merge:true})));
await t("A reads shop doc", assertSucceeds(getDoc(doc(a,"shops/A"))));
await t("A cannot read legacy flat", assertFails(getDoc(doc(a,"nelly_sales/old"))));
await t("expired can read", assertSucceeds(getDoc(doc(x,"shops/X"))));
await t("expired cannot write", assertFails(setDoc(doc(x,"shops/X/nelly_sales/n"),{})));
await t("anon cannot read", assertFails(getDoc(doc(anon,"shops/A/nelly_sales/s1"))));
console.log(r.join("\n")); await env.cleanup();
